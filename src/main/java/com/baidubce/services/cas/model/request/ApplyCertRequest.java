package com.baidubce.services.cas.model.request;

import java.sql.Timestamp;
import java.util.ArrayList;
import java.util.List;

import com.baidubce.auth.BceCredentials;
import com.baidubce.model.AbstractBceRequest;
import com.baidubce.services.cas.model.CasConstants;
import com.baidubce.services.cas.model.type.AuthType;
import com.baidubce.services.cas.model.type.EncryptionType;
import com.baidubce.services.cas.model.type.HashAlgo;
import com.baidubce.services.cas.model.type.IdentityType;
import com.baidubce.services.cas.model.type.OrgIdentityType;
import com.baidubce.services.cas.model.type.VerifyPlat;
import com.fasterxml.jackson.annotation.JsonFormat;
import com.fasterxml.jackson.annotation.JsonIgnoreProperties;
import com.fasterxml.jackson.annotation.JsonInclude;
import com.fasterxml.jackson.annotation.JsonProperty;

import lombok.AllArgsConstructor;
import lombok.Data;
import lombok.EqualsAndHashCode;
import lombok.NoArgsConstructor;

/**
 * Request of applying for a certificate.
 */
@Data
@EqualsAndHashCode(callSuper = false)
@JsonInclude(JsonInclude.Include.NON_NULL)
@JsonIgnoreProperties(ignoreUnknown = true)
public class ApplyCertRequest extends AbstractBceRequest {
    /**
     * Primary domain.
     */
    @JsonProperty("domain")
    private String primaryDomain;
    /**
     * Encryption algorithm, see EncryptionType.
     */
    @JsonProperty("algorithm")
    private String encryptionType = EncryptionType.RSA.name();
    /**
     * Key strength, see EncryptionStrength.
     */
    @JsonProperty("strength")
    private String encryptionStrength;
    /**
     * Digest algorithm, see HashAlgo.
     */
    private String hashAlgo = HashAlgo.SHA384.name();
    /**
     * CSR content. When absent the CSR is generated by the server.
     */
    private String csr;
    /**
     * Domain control validation method, see AuthType.
     */
    @JsonProperty("verifyMode")
    private String authType = AuthType.DNS.name();
    /**
     * Additional domains.
     */
    @JsonProperty("multiDomain")
    private List<String> bindDomains = new ArrayList<>();
    /**
     * Company name.
     */
    private String company = "default company";
    /**
     * Department.
     */
    @JsonProperty("department")
    private String division = "default division";
    /**
     * Address.
     */
    private String address = "default address";
    /**
     * Postal code.
     */
    private String postalCode = "default code";
    /**
     * Organization identity document type. Required by CFCA certificates.
     */
    private OrgIdentityType orgIdentityType;
    /**
     * Organization identity document number. Required by CFCA certificates.
     */
    private String orgRegNumber;
    /**
     * Company phone.
     */
    @JsonProperty("companyPhone")
    private String phone = "0000000";
    /**
     * Region of the company.
     */
    private Region region = new Region("000000", "000000", "086");
    /**
     * Given name of the order administrator.
     */
    @JsonProperty("orderGivenName")
    private String adminFirstName = "default first name";
    /**
     * Family name of the order administrator.
     */
    @JsonProperty("orderFamilyName")
    private String adminLastName = "default last name";
    /**
     * Position of the order administrator.
     */
    @JsonProperty("orderPosition")
    private String adminTitle = "default title";
    /**
     * Email of the order administrator.
     */
    @JsonProperty("orderEmail")
    private String adminEmail = "ssl_no_reply@baidu.com";
    /**
     * Phone of the order administrator.
     */
    @JsonProperty("orderPhone")
    private String adminPhone = "0000000";
    /**
     * Identity document type of the order administrator. Required by CFCA certificates.
     */
    private IdentityType adminIdentityType;
    /**
     * Identity document number of the order administrator. Required by CFCA certificates.
     */
    private String adminIdNumber;
    /**
     * Given name of the technical contact.
     */
    @JsonProperty("techGivenName")
    private String techFirstName = "default first name";
    /**
     * Family name of the technical contact.
     */
    @JsonProperty("techFamilyName")
    private String techLastName = "default last name";
    /**
     * Position of the technical contact.
     */
    @JsonProperty("techPosition")
    private String techTitle = "default title";
    /**
     * Email of the technical contact.
     */
    private String techEmail = "ssl_no_reply@baidu.com";
    /**
     * Phone of the technical contact.
     */
    private String techPhone = "0000000";
    /**
     * Identity document type of the technical contact. Required by CFCA certificates.
     */
    private IdentityType techIdentityType;
    /**
     * Identity document number of the technical contact. Required by CFCA certificates.
     */
    private String techIdNumber;
    /**
     * Platform used to verify the organization information.
     */
    private VerifyPlat verifyPlat = VerifyPlat.NONE;
    /**
     * Verification time.
     */
    @JsonFormat(shape = JsonFormat.Shape.STRING, pattern = "yyyy-MM-dd HH:mm:ss", timezone = CasConstants.UTC)
    private Timestamp verifyTime;

    @Override
    public AbstractBceRequest withRequestCredentials(BceCredentials credentials) {
        this.setRequestCredentials(credentials);
        return this;
    }

    /**
     * Region of the company.
     */
    @Data
    @NoArgsConstructor
    @AllArgsConstructor
    @JsonInclude(JsonInclude.Include.NON_NULL)
    @JsonIgnoreProperties(ignoreUnknown = true)
    public static class Region {
        /**
         * Province code.
         */
        private String province;
        /**
         * City code.
         */
        private String city;
        /**
         * Country code.
         */
        private String country;
    }
}
