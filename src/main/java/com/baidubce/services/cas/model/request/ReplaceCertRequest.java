package com.baidubce.services.cas.model.request;

import java.util.List;

import com.baidubce.auth.BceCredentials;
import com.baidubce.model.AbstractBceRequest;
import com.baidubce.services.cas.model.type.HashAlgo;
import com.fasterxml.jackson.annotation.JsonIgnoreProperties;
import com.fasterxml.jackson.annotation.JsonInclude;
import com.fasterxml.jackson.annotation.JsonProperty;

import lombok.Data;
import lombok.EqualsAndHashCode;

/**
 * Request of re-issuing (replacing) an existing certificate.
 */
@Data
@EqualsAndHashCode(callSuper = false)
@JsonInclude(JsonInclude.Include.NON_NULL)
@JsonIgnoreProperties(ignoreUnknown = true)
public class ReplaceCertRequest extends AbstractBceRequest {
    /**
     * Certificate id.
     */
    @JsonProperty("productId")
    private String certId;
    /**
     * Primary domain.
     */
    private String domain;
    /**
     * Domain control validation method, see AuthType.
     */
    @JsonProperty("verifyMode")
    private String authType;
    /**
     * Encryption algorithm, see EncryptionType.
     */
    @JsonProperty("algorithm")
    private String encryptionType;
    /**
     * Key strength, see EncryptionStrength.
     */
    @JsonProperty("strength")
    private String encryptionStrength;
    /**
     * Digest algorithm, see HashAlgo.
     */
    private String hashAlgo = HashAlgo.SHA384.name();
    /**
     * Additional domains.
     */
    private List<String> multiDomain;
    /**
     * Order id, optional.
     */
    private String orderId;
    /**
     * CSR content. When absent the CSR is generated by the server.
     */
    private String csr;
    /**
     * Query type, "normal" by default.
     */
    private String type = "normal";

    @Override
    public AbstractBceRequest withRequestCredentials(BceCredentials credentials) {
        this.setRequestCredentials(credentials);
        return this;
    }
}
